// Scratch proof of Node's synthetic failed-file entry. No Chrome process.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const directory = await mkdtemp(join(tmpdir(), 'ait227-reporter-'));
const fixture = join(directory, 'file-exit.mjs');
await writeFile(fixture, `import { test, after } from 'node:test';
for (let i=0; i<18; i++) test('entry '+i, () => {});
after(() => { process.exitCode=1; });
`);
const child = spawn(process.execPath, ['--test', '--test-reporter=tap', fixture], { env: { PATH: process.env.PATH, HOME: directory, TMPDIR: directory }, stdio: ['ignore','pipe','pipe'] });
let output = ''; child.stdout.on('data', data=>output+=data); child.stderr.on('data', data=>output+=data);
const exit = await new Promise(resolve=>child.on('close',resolve));
console.log(output);
assert.equal(exit,1);
assert.match(output, /# tests 19/u);
assert.match(output, /# pass 18/u);
assert.match(output, /failureType: 'testCodeFailure'/u);
console.log('18 passing tests + one synthetic failed-file entry = 19; one reporter, no retries.');
