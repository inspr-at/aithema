import { test } from 'node:test';
import assert from 'node:assert/strict';
import { manifest } from '../src/manifest.js';
import { config } from './fixtures.js';

import { binding, provider } from './admission-fixtures.js';
const session = { id: 'fixture', consentRevision: 1 };
const policy = { endpoints: ['https://api.x.ai'] };

test('AIT-346: exact direct recipient consent in both languages', () => {
  const items = manifest.presentation.translations.map(row => row.consentItem);
  assert.deepEqual(items, [
    { id: 'voice-xai', version: 1, title: 'Sprache mit Grok Voice (xAI)',
      recipients: 'xAI (SpaceXAI LLC), USA. Verarbeitung international; kein zugesicherter Verarbeitungsort.',
      text: 'xAI verarbeitet Ihre Spracheingabe, Transkriptionen, die auszugebenden Antworttexte und notwendige technische Verbindungsdaten direkt für Spracherkennung und Sprachausgabe. Die Antworten entstehen über den separat freigegebenen KI-Modellanbieter.' },
    { id: 'voice-xai', version: 1, title: 'Voice with Grok Voice (xAI)',
      recipients: 'xAI (SpaceXAI LLC), United States. International processing; no guaranteed processing region.',
      text: 'xAI directly processes your speech input, transcripts, answer text to be spoken and necessary technical connection data for speech recognition and synthesis. Answers are generated by the separately authorised AI model provider.' },
  ]);
});
for (const [label, mutate, reason] of [
  ['missing account', p => { p.config = undefined; }, 'Grok account configuration required (private ZDR/DPA references)'],
  ['missing ZDR reference', p => { delete p.config.accountEvidence.zdrRef; }, 'Invalid Grok Voice private configuration (private ZDR/DPA account evidence required)'],
  ['wrong account', p => { p.componentBindings.stt.accountRef = 'private:other'; }, 'Grok component binding mismatch'],
  ['model consent reused for audio', p => { p.binding.legal.purpose = 'models-international'; }, 'Grok requires voice-xai v1 direct-recipient binding'],
]) test(`AIT-346: ${label} is explicitly unavailable`, async () => {
  const values = { config: structuredClone(config), binding: binding(),
    componentBindings: { stt: binding('grok-voice-transcribe-2.0'), tts: binding('grok-voice-tts') } };
  mutate(values); const p = provider(values);
  assert.deepEqual(await p.health(), { available: false, reason });
});
for (const denied of ['missing', 'stale', 'old-version', 'model-only']) test(`AIT-346: ${denied} audio consent denies before claims`, async () => {
  const p = provider({ consent: { async coverage({ scope, consentRevision }) {
    return { ...scope, scope, consentRevision, covered: denied !== 'missing', checkedAt: Date.now() - (denied === 'stale' ? 2000 : 0),
      expiresAt: Date.now() + 60000, itemVersion: denied === 'old-version' ? 0 : 1,
      purpose: denied === 'model-only' ? 'models-international' : scope.purpose };
  } } });
  assert.equal(await p.ports.serverAdapter.admissionReason({ session, preset: 'best', policy }, { deadlineAt: Date.now() + 2000 }), 'current processing consent required');
});
test('AIT-346: complete audio scope admits only permitted endpoint and preset', async () => {
  const p = provider(), adapter = p.ports.serverAdapter;
  assert.equal(await adapter.admissionReason({ session, preset: 'best', policy }, {}), null);
  assert.equal(await adapter.admissionReason({ session, preset: 'eu', policy }, {}), 'recipient seat outside eu');
  assert.equal(await adapter.admissionReason({ session, preset: 'best', policy: { endpoints: [] } }, {}), 'endpoint not allowed');
  assert.deepEqual(adapter.processingScopes().map(s => [s.purpose, s.operation]), [['voice-xai', 'stream'], ['voice-xai', 'speak']]);
});
